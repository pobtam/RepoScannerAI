-- 0005_reports: issued reports (VM-ADR-15).
--
-- Every report anchors to a run, is immutable once issued, carries a content
-- hash, and stores the query that produced it.
--
-- A report generated from live state cannot be regenerated, so it cannot be
-- cited or verified — which is most of the value of issuing one. Anchoring makes
-- reproducibility a property rather than a hope; the hash is what lets a copy
-- found in an email thread eighteen months later be checked against the
-- original; and storing the query is what makes "regenerate this" a defined
-- operation rather than a reconstruction from memory.

CREATE TABLE reports (
  id              TEXT PRIMARY KEY,
  -- The run this report describes. Reports cannot be generated for "right now":
  -- the most recent anchor is the latest completed run, and the interface must
  -- say so rather than silently anchoring (VM-ADR-15).
  anchor_run_id   TEXT NOT NULL REFERENCES runs(id),
  kind            TEXT NOT NULL,          -- fleet | repo
  repo            TEXT REFERENCES repos(name),
  template        TEXT NOT NULL,
  -- The query that produced it, stored verbatim so the report can be
  -- regenerated byte-identically rather than approximately.
  query           JSONB NOT NULL,
  -- sha256 of the authoritative JSON document.
  content_hash    TEXT NOT NULL,
  content         JSONB NOT NULL,
  issued_at       TIMESTAMPTZ NOT NULL,
  issued_by       TEXT,
  -- Immutability with supersession rather than editing: editing in place
  -- destroys the audit trail a superseded report preserves.
  supersedes      TEXT REFERENCES reports(id),
  superseded_by   TEXT REFERENCES reports(id),
  -- Redaction is recorded on the artifact: a report delivered below the
  -- generator's privilege level must say that redaction occurred, not silently
  -- omit rows (VM-F-75x).
  redacted        BOOLEAN NOT NULL DEFAULT FALSE,
  withheld_count  INT NOT NULL DEFAULT 0
);
CREATE INDEX reports_anchor_idx ON reports (anchor_run_id);
CREATE INDEX reports_repo_idx ON reports (repo, issued_at DESC);
CREATE UNIQUE INDEX reports_hash_idx ON reports (content_hash, anchor_run_id);
